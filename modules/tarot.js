const RANKS = ['에이스', '2', '3', '4', '5', '6', '7', '8', '9', '10', '시종', '기사', '여왕', '왕']

function buildDeck () {
  const deck = MAJORS.map(([name, file, up, rev, essence, upAdv, revAdv]) =>
    ({ name, file, up, rev, essence, upAdv, revAdv, arcana: '메이저' }))
  for (const suit of SUITS) {
    suit.cards.forEach(([up, rev, essence, upAdv, revAdv], i) => {
      const num = String(i + 1).padStart(2, '0')
      deck.push({
        name: `${suit.ko} ${RANKS[i]}`,
        file: `${suit.key}${num}.jpg`,
        up,
        rev,
        essence,
        upAdv,
        revAdv,
        arcana: `마이너 · ${suit.theme}`
      })
    })
  }
  return deck
}

const DECK = buildDeck()

// 카드 의미(essence) + 방향별 고유 조언(upAdv/revAdv)을 엮는다.
// 조언은 카드마다 다른 내용이라, 위치(과거/현재/미래)는 임베드 헤더 라벨로만 구분한다.
function describe ({ card, reversed }) {
  const keyword = reversed ? card.rev : card.up
  const advice = reversed ? card.revAdv : card.upAdv
  return `📖 ${card.essence}\n\n💡 **${keyword}**\n${advice}`
}

// Fisher-Yates 셔플을 shuffleCount번 반복한 뒤 위에서 3장을 뽑는다.
// 각 카드는 50% 확률로 역방향. 위치는 과거/현재/미래 순.
function draw (shuffleCount) {
  const deck = DECK.slice()
  const rounds = Math.max(1, Math.min(shuffleCount || 1, 1000))
  for (let r = 0; r < rounds; r++) {
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1))
      ;[deck[i], deck[j]] = [deck[j], deck[i]]
    }
  }
  const positions = ['과거', '현재', '미래']
  return deck.slice(0, 3).map((card, i) => {
    const reversed = Math.random() < 0.5
    const item = { position: positions[i], card, reversed }
    return {
      ...item,
      meaning: reversed ? card.rev : card.up,
      prose: describe(item),
      imageUrl: imageUrl(card.file)
    }
  })
}

module.exports = { draw, describe, imageUrl, DECK }
