const crypto = require('crypto')

// 위키미디어 커먼즈는 파일명 md5 해시로 경로가 정해진다.
// 예) RWS_Tarot_00_Fool.jpg → md5=90ba... → /commons/9/90/RWS_Tarot_00_Fool.jpg
// 덕분에 URL을 하드코딩하지 않고 파일명만으로 계산할 수 있다. (라이더-웨이트 1909, 퍼블릭 도메인)
function imageUrl (file) {
  const h = crypto.createHash('md5').update(file).digest('hex')
  return `https://upload.wikimedia.org/wikipedia/commons/${h[0]}/${h.slice(0, 2)}/${file}`
}

