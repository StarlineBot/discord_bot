function pick (rng, arr) { return arr[Math.floor(rng() * arr.length)] }
function star (rng) { return 1 + Math.floor(rng() * 5) } // 1~5

// 별점 톤에 맞는 기운 묘사 + 실천 팁 조합
function catFortune (rng, open, tip) {
  const s = star(rng)
  const bucket = s >= 4 ? 'good' : s === 3 ? 'mid' : 'low'
  return { star: s, msg: `${pick(rng, open[bucket])} ${pick(rng, tip)}` }
}

// dateStr: 'YYYY-MM-DD'(KST) 권장 → 하루 단위 고정
function buildDailyFortune (userId, dateStr) {
  const rng = mulberry32(hashSeed(`${userId}:${dateStr}`))
  return {
    total: catFortune(rng, TOTAL_OPEN, TOTAL_TIP),
    love: catFortune(rng, LOVE_OPEN, LOVE_TIP),
    money: catFortune(rng, MONEY_OPEN, MONEY_TIP),
    work: catFortune(rng, WORK_OPEN, WORK_TIP),
    luckyNumber: 1 + Math.floor(rng() * 99),
    luckyColor: pick(rng, COLORS),
    luckyDirection: pick(rng, DIRS),
    luckyItem: pick(rng, ITEMS),
    luckyTime: pick(rng, TIMES),
    mood: pick(rng, MOODS),
    advice: pick(rng, ADVICE)
  }
}

